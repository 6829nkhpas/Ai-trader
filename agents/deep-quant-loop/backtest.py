# ── Calibration (reliability) measurement (R12.1–R12.5) ──────────────────────

# Sentinel reported for a probability bin that contains zero recorded forecasts.
# An empty bin has no mean predicted probability and no realized fraction, so we
# report this string rather than dividing by zero (R12.4). The scalar
# ``calibration_error`` uses the same sentinel when EVERY bin is empty (no
# non-empty bin to average over).
_CALIBRATION_NA = "n/a"


def _calibration_from_records(records, bins) -> dict:
    """Bin (Up_Probability, realized-up) records and report reliability stats.

    ``records`` is a list of ``{"up_probability": float in [0, 1],
    "went_up": bool}`` dicts. The ``[0, 1]`` probability range is partitioned into
    ``bins`` equal-width bins; a record is placed in bin
    ``min(int(up_probability * bins), bins - 1)`` so the ``up_probability == 1.0``
    edge falls in the LAST bin rather than overflowing (R12.2).

    For each NON-EMPTY bin we report its ``count``, the ``mean_predicted`` (mean
    of the bin's ``up_probability`` values), and the ``realized_up_fraction`` (the
    fraction of the bin's records whose ``went_up`` is True) — R12.2. Each EMPTY
    bin is reported with ``count`` 0 and ``mean_predicted`` / ``realized_up_fraction``
    set to the ``"n/a"`` sentinel rather than dividing by zero (R12.4).

    ``calibration_error`` is the mean absolute difference between
    ``mean_predicted`` and ``realized_up_fraction`` over the NON-EMPTY bins
    (R12.3); when every bin is empty it is the same ``"n/a"`` sentinel (no
    non-empty bin to average). ``total_records`` is the number of valid records
    binned.

    Pure (no input mutation), never divides by zero, and never raises — a
    non-list ``records``, malformed record dicts, out-of-range/non-finite
    probabilities, and a non-positive/garbage ``bins`` are all tolerated by
    coercion and skipping.
    """
    # Coerce the bin count to a positive integer; anything unparseable or < 1
    # collapses to a single [0, 1] bin so the partition is always well-formed.
    try:
        n_bins = int(bins)
    except (TypeError, ValueError):
        n_bins = 0
    if n_bins < 1:
        n_bins = 1

    counts = [0] * n_bins
    prob_sums = [0.0] * n_bins
    up_counts = [0] * n_bins
    total = 0

    for rec in records if isinstance(records, list) else []:
        if not isinstance(rec, dict):
            continue
        p = rec.get("up_probability")
        # Only finite probabilities inside [0, 1] are binnable.
        if not _is_num(p) or p < 0.0 or p > 1.0:
            continue
        idx = int(p * n_bins)
        if idx >= n_bins:           # the up_probability == 1.0 edge lands here
            idx = n_bins - 1
        elif idx < 0:               # defensive; p >= 0 already guaranteed
            idx = 0
        counts[idx] += 1
        prob_sums[idx] += p
        if bool(rec.get("went_up")):
            up_counts[idx] += 1
        total += 1

    width = 1.0 / n_bins
    bins_report = []
    abs_errors = []
    for k in range(n_bins):
        lower = round(k * width, 10)
        upper = round((k + 1) * width, 10)
        if counts[k] == 0:
            bins_report.append({
                "lower": lower,
                "upper": upper,
                "count": 0,
                "mean_predicted": _CALIBRATION_NA,
                "realized_up_fraction": _CALIBRATION_NA,
            })
            continue
        mean_predicted = prob_sums[k] / counts[k]
        realized_up_fraction = up_counts[k] / counts[k]
        abs_errors.append(abs(mean_predicted - realized_up_fraction))
        bins_report.append({
            "lower": lower,
            "upper": upper,
            "count": counts[k],
            "mean_predicted": round(mean_predicted, 6),
            "realized_up_fraction": round(realized_up_fraction, 6),
        })

    calibration_error = (
        round(sum(abs_errors) / len(abs_errors), 6) if abs_errors else _CALIBRATION_NA
    )
    return {
        "bins": bins_report,
        "calibration_error": calibration_error,
        "total_records": total,
    }


def calibrate_forecast(symbol: str, timeframe: str, limit: int = 3000,
                       candles: Optional[List[dict]] = None,
                       cfg: Optional[BacktestConfig] = None,
                       bins: Optional[int] = None,
                       source: str = "auto") -> dict:
    """Measure whether the forecaster's Up_Probability matches realized outcomes.

    Walks the candle history and, for every bar ``i`` that has a valid next bar
    ``i + 1``, computes the forecast from ONLY ``candles[: i + 1]`` (the window at
    or before bar ``i`` — no look-ahead, R12.1) via the SAME ``forecaster.forecast``
    the live tool path uses (R12.5; the calibration never reimplements the forecast
    math). When that produces a usable Forecast_Label with a finite Up_Probability,
    the predicted probability is paired with the realized direction of the next bar
    — ``went_up = close_{i+1} > close_i`` (R12.1) — and collected as a record.
    Bars whose forecast is an Unavailable_Marker (e.g. insufficient early history)
    or whose adjacent closes are non-numeric are skipped.

    The records are passed to ``_calibration_from_records`` with ``bins`` (or the
    resolved ``prob_bins`` default when not supplied), and the per-bin report,
    scalar calibration error, and paired-record count are returned alongside the
    run's ``symbol`` / ``timeframe`` / ``candles`` context. Pure given ``candles``
    (no journal writes); the forecaster never touches the network.
    """
    cfg = cfg or BacktestConfig()
    if candles is None:
        candles = _resolve_candles(symbol, timeframe, limit, source)

    # Resolve the forecaster parameters ONCE, reusing the SAME resolver the live
    # get_forecast tool and the backtest comparison use (R12.5, R14.5).
    fc_config = forecaster.resolve_forecaster_config()

    n = len(candles) if isinstance(candles, list) else 0
    records: List[dict] = []
    for i in range(n - 1):
        cur = candles[i]
        nxt = candles[i + 1]
        cur_close = cur.get("close") if isinstance(cur, dict) else None
        nxt_close = nxt.get("close") if isinstance(nxt, dict) else None
        # Guard non-numeric closes — the realized direction is undefined without
        # two finite closes (R12.1).
        if not (_is_num(cur_close) and _is_num(nxt_close)):
            continue

        # Forecast from ONLY candles at or before bar i — the point-in-time slice
        # candles[: i + 1] carries no later candles, so there is no look-ahead
        # (R12.1). The same forecaster as the live tool path (R12.5).
        fc_result = forecaster.forecast(
            candles[: i + 1], fc_config, symbol=symbol, timeframe=timeframe,
        )
        if not isinstance(fc_result, dict) or fc_result.get("unavailable") is True:
            continue
        up_probability = fc_result.get("up_probability")
        if not _is_num(up_probability):
            continue

        # Pair the predicted Up_Probability with the realized next-bar direction.
        records.append({
            "up_probability": up_probability,
            "went_up": nxt_close > cur_close,
        })

    report = _calibration_from_records(records, bins or fc_config.prob_bins)
    return {
        "symbol": symbol,
        "timeframe": timeframe,
        "candles": n,
        **report,
    }


# ── Discovery & batch seeding ─────────────────────────────────────────────────

def discover_symbols(source: str = "questdb") -> List[str]:
    """Return every symbol present in the QuestDB archive (daily ∪ intraday)."""
    symbols = set()
    for table in ("historical_candles", "historical_intraday"):
        try:
            r = httpx.get(
                f"{QUESTDB_HTTP_URL}/exec",
                params={"query": f"SELECT DISTINCT symbol FROM {table}"},
                timeout=15.0,
            )
            r.raise_for_status()
            body = r.json()
            for row in body.get("dataset", []) or []:
                if row and row[0]:
                    symbols.add(row[0])
        except Exception as e:
            print(f"[Backtest_Seeder] symbol discovery from {table} failed: {e}")
    return sorted(symbols)


def discover_intraday_timeframes() -> List[str]:
    """Return the distinct intraday timeframe labels stored in QuestDB."""
    try:
        r = httpx.get(
            f"{QUESTDB_HTTP_URL}/exec",
            params={"query": "SELECT DISTINCT timeframe FROM historical_intraday"},
            timeout=15.0,
        )
        r.raise_for_status()
        body = r.json()
        tfs = [row[0] for row in body.get("dataset", []) or [] if row and row[0]]
        return sorted(tfs)
    except Exception as e:
        print(f"[Backtest_Seeder] intraday timeframe discovery failed: {e}")
        return []


def seed_batch(symbols: List[str], timeframes: List[str], limit: int = 3000,
               cfg: Optional[BacktestConfig] = None, purge_first: bool = True,
               dry_run: bool = False, source: str = "auto") -> dict:
    """Seed every (symbol × timeframe) combination.

    Purges existing backtest rows ONCE per symbol (covering all its timeframes)
    before seeding, so re-runs stay idempotent without wiping earlier timeframes
    mid-batch. Each cell is isolated: a failure (e.g. no data for that
    symbol/timeframe) is recorded and the batch continues.
    """
    cfg = cfg or BacktestConfig()
    cells = []
    totals = {"signals_scored": 0, "wins": 0, "losses": 0, "written": 0, "errors": 0}

    for sym in symbols:
        if purge_first and not dry_run:
            removed = journal.purge(source="backtest", symbol=sym)
            if removed:
                print(f"[Backtest_Seeder] purged {removed} existing backtest row(s) for {sym}.")
        for tf in timeframes:
            try:
                res = seed(sym, tf, limit=limit, cfg=cfg, purge_first=False,
                           dry_run=dry_run, source=source)
                cells.append({
                    "symbol": sym, "timeframe": tf,
                    "signals_scored": res.get("signals_scored", 0),
                    "wins": res.get("wins", 0), "losses": res.get("losses", 0),
                    "written": res.get("written", 0),
                })
                totals["signals_scored"] += res.get("signals_scored", 0)
                totals["wins"] += res.get("wins", 0)
                totals["losses"] += res.get("losses", 0)
                totals["written"] += res.get("written", 0)
                print(f"[Backtest_Seeder] {sym}/{tf}: {res.get('signals_scored',0)} scored "
                      f"({res.get('wins',0)}W/{res.get('losses',0)}L), {res.get('written',0)} written.")
            except Exception as e:
                totals["errors"] += 1
                cells.append({"symbol": sym, "timeframe": tf, "error": str(e)})
                print(f"[Backtest_Seeder] {sym}/{tf}: SKIPPED ({e})")

    scored = totals["wins"] + totals["losses"]
    return {
        "symbols": len(symbols),
        "timeframes": timeframes,
        "totals": totals,
        "overall_win_rate": round(totals["wins"] / scored, 4) if scored else None,
        "dry_run": dry_run,
        "cells": cells,
    }


# ── CLI ───────────────────────────────────────────────────────────────────────

def main() -> None:
    p = argparse.ArgumentParser(description="Seed the Trade_Journal from historical candles.")
    p.add_argument("--symbol", default=None, help="Trading symbol, e.g. RELIANCE (omit with --all-symbols)")
    p.add_argument("--all-symbols", action="store_true", help="Seed every symbol found in the QuestDB archive")
    p.add_argument("--timeframe", default="1d",
                   help="Timeframe(s), comma-separated (e.g. '1d,15m,1h'). Default 1d")
    p.add_argument("--all-timeframes", action="store_true",
                   help="Seed 1d plus every intraday timeframe present in QuestDB")
    p.add_argument("--limit", type=int, default=3000, help="Candles to fetch per symbol/timeframe")
    p.add_argument("--source", choices=["auto", "questdb", "server"], default="auto",
                   help="Candle source: auto (QuestDB then tool server), questdb, or server")
    p.add_argument("--candles-file", default=None,
                   help="Load candles from a JSON file (single symbol/timeframe only)")
    p.add_argument("--no-purge", action="store_true", help="Do not purge existing backtest rows first")
    p.add_argument("--dry-run", action="store_true", help="Compute and print stats without writing to the journal")

    # ── Rule tuning knobs ────────────────────────────────────────────────────
    p.add_argument("--rr", type=float, default=None, help="Risk:Reward multiple (target = RR x stop). Default 2.0")
    p.add_argument("--atr-mult", type=float, default=None, help="Stop distance as a multiple of ATR. Default 1.5")
    p.add_argument("--horizon", type=int, default=None, help="Max bars to let a trade resolve. Default 200")
    p.add_argument("--cooldown", type=int, default=None, help="Min bars between successive signals. Default 5")
    p.add_argument("--lookback", type=int, default=None, help="Bars of context per decision. Default 120")
    p.add_argument("--record-expired", action="store_true",
                   help="Also record trades that never hit stop/target (as 'expired')")
    args = p.parse_args()

    # Build the config from any provided knobs (unset → dataclass defaults).
    cfg = BacktestConfig()
    if args.rr is not None:
        cfg.risk_reward = args.rr
    if args.atr_mult is not None:
        cfg.atr_stop_mult = args.atr_mult
    if args.horizon is not None:
        cfg.max_horizon_bars = args.horizon
    if args.cooldown is not None:
        cfg.cooldown_bars = args.cooldown
    if args.lookback is not None:
        cfg.lookback = args.lookback
    if args.record_expired:
        cfg.record_unresolved = True

    # Resolve the timeframe list.
    if args.all_timeframes:
        timeframes = ["1d"] + [tf for tf in discover_intraday_timeframes() if tf.lower() not in _DAILY_TIMEFRAMES]
    else:
        timeframes = [tf.strip() for tf in args.timeframe.split(",") if tf.strip()]
    if not timeframes:
        print("[Backtest_Seeder] No timeframes resolved.")
        raise SystemExit(1)

    # ── Single-symbol file mode (kept simple: one symbol, one timeframe) ─────
    if args.candles_file:
        if not args.symbol:
            print("[Backtest_Seeder] --candles-file requires --symbol.")
            raise SystemExit(1)
        candles = _load_candles_file(args.candles_file)
        summary = seed(args.symbol, timeframes[0], limit=args.limit, candles=candles,
                       cfg=cfg, purge_first=not args.no_purge, dry_run=args.dry_run)
        print("\n[Backtest_Seeder] Summary:")
        print(json.dumps(summary, indent=2))
        return

    # ── Resolve the symbol list ──────────────────────────────────────────────
    if args.all_symbols:
        symbols = discover_symbols(args.source)
        if not symbols:
            print("[Backtest_Seeder] No symbols discovered in QuestDB.")
            raise SystemExit(1)
        print(f"[Backtest_Seeder] Discovered {len(symbols)} symbol(s): {', '.join(symbols)}")
    elif args.symbol:
        symbols = [args.symbol]
    else:
        print("[Backtest_Seeder] Provide --symbol or --all-symbols.")
        raise SystemExit(1)

    # ── Single symbol + single timeframe → detailed per-setup summary ────────
    if len(symbols) == 1 and len(timeframes) == 1:
        try:
            summary = seed(symbols[0], timeframes[0], limit=args.limit, cfg=cfg,
                           purge_first=not args.no_purge, dry_run=args.dry_run, source=args.source)
        except Exception as e:
            print(f"[Backtest_Seeder] FAILED: {e}")
            raise SystemExit(1)
        print("\n[Backtest_Seeder] Summary:")
        print(json.dumps(summary, indent=2))
        return

    # ── Batch mode (multi-symbol and/or multi-timeframe) ─────────────────────
    summary = seed_batch(symbols, timeframes, limit=args.limit, cfg=cfg,
                         purge_first=not args.no_purge, dry_run=args.dry_run, source=args.source)
    print("\n[Backtest_Seeder] Batch Summary:")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
