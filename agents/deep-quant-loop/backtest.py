# ── Scoring against future candles (mirrors journal._score_one) ───────────────

def _score_signal(decision: dict, future: List[dict], cfg: BacktestConfig):
    """Score a decision against the bars that follow it.

    Returns (status, outcome_price, outcome_at_seconds, r_multiple) or None when
    there are no future bars at all. Worst-case: a bar touching both levels is a
    loss. A trade that resolves neither within ``max_horizon_bars`` is expired.
    """
    action = decision["action"]
    entry = decision["entry"]
    sl = decision["stop_loss"]
    tp = decision["take_profit"]
    risk = abs(entry - sl)
    if risk <= 0:
        return None
    rr = abs(tp - entry) / risk

    horizon = future[: cfg.max_horizon_bars]
    if not horizon:
        return None

    last_ts = None
    for c in horizon:
        hi, lo, ts = c.get("high"), c.get("low"), c.get("timestamp_ms")
        if not (_is_num(hi) and _is_num(lo)):
            continue
        last_ts = ts if _is_num(ts) else last_ts
        out_at = (ts / 1000.0) if _is_num(ts) else None
        hit_tp = hi >= tp if action == "BUY" else lo <= tp
        hit_sl = lo <= sl if action == "BUY" else hi >= sl
        if hit_sl and hit_tp:
            return "loss", sl, out_at, -1.0
        if hit_tp:
            return "win", tp, out_at, round(rr, 4)
        if hit_sl:
            return "loss", sl, out_at, -1.0

    return "expired", None, (last_ts / 1000.0 if _is_num(last_ts) else None), None


# ── Managed scoring via the Trade_Manager (R7.1, R7.2) ───────────────────────
# A managed seeded trade is scored by the SINGLE source of truth for the
# exit-simulation math — ``trade_manager.simulate_plan`` — never by reimplementing
# the multi-leg fill / breakeven / trail logic here (R7.2, AD-2). The backtest
# path and the live journal-scoring path both call back into the same simulator,
# feeding only different candle windows. A single-target seeded trade keeps using
# the legacy ``_score_signal`` path above so its outcome is byte-for-byte today's.

def _managed_outcome(result, horizon: List[dict]):
    """Map a ``SimulationResult`` onto ``_score_signal``'s outcome tuple.

    Returns (status, outcome_price, outcome_at_seconds, r_multiple) or None,
    matching the shape ``_score_signal`` returns so the seeding path stays
    uniform across managed and single-target trades:

      * ``invalid`` (zero initial-stop distance) -> None (skip, as ``_score_signal``
        skips a zero-risk bracket).
      * ``open``    (no candle reached the stop and never fully scaled out within
        the horizon) -> ("expired", None, last-bar-ts, None).
      * ``resolved`` with a positive fraction-weighted ``Realized_R`` -> a "win"
        at the final fill price / time and that R; a non-positive ``Realized_R``
        -> a "loss" (R6.4 win/loss convention: positive R is a win).
    """
    if result.status == "invalid":
        return None
    if result.status == "open":
        last_ts = None
        for c in horizon:
            ts = c.get("timestamp_ms") if isinstance(c, dict) else None
            if _is_num(ts):
                last_ts = ts
        return "expired", None, (last_ts / 1000.0 if _is_num(last_ts) else None), None

    # resolved — derive the binary status from the multi-leg Realized_R and report
    # the final fill (the last recorded exit in the Exit_Breakdown) as the outcome.
    realized_r = result.realized_r
    status = "win" if (_is_num(realized_r) and realized_r > 0) else "loss"
    last_fill = result.fills[-1] if result.fills else None
    out_price = last_fill.price if last_fill is not None else None
    out_at = (last_fill.timestamp_ms / 1000.0) if (last_fill is not None and _is_num(last_fill.timestamp_ms)) else None
    r_mult = round(realized_r, 4) if _is_num(realized_r) else None
    return status, out_price, out_at, r_mult


def _score_signal_managed(plan, future: List[dict], cfg: BacktestConfig, tm_config):
    """Score a managed ``ManagementPlan`` against the bars that follow the signal.

    Invokes ``trade_manager.simulate_plan`` against the candles at or after the
    signal's entry candle (the caller passes ``candles[i + 1:]`` — the bars after
    the entry bar's close, the same window the single-target ``_score_signal``
    uses, capped to ``max_horizon_bars``), reusing the Trade_Manager functions
    rather than reimplementing the exit logic (R7.1, R7.2). Returns
    ``(outcome_tuple_or_None, simulation_result_or_None)`` so the caller can both
    record the outcome and cite the simulated ``Exit_Breakdown`` in the
    defensibility record. Never raises — ``simulate_plan`` reports degeneracy as
    data (open / invalid), not exceptions.
    """
    horizon = future[: cfg.max_horizon_bars]
    if not horizon:
        return None, None
    result = trade_manager.simulate_plan(plan, horizon, tm_config)
    return _managed_outcome(result, horizon), result


def _management_defensibility_entry(plan, sim_result) -> dict:
    """Map a Management_Plan (+ optional simulation) to the defensibility entry.

    Labels a seeded trade with its management style so the journal's
    management-style fingerprint can tag it (``tm:<value>``) and per-management-
    style win-rate / expectancy become measurable (R7.3). Mirrors the shape
    ``graph._management_entry`` (task 12) writes and the journal management-style
    derivation (task 9.2) reads, so seeded trades are labelled identically to live
    LLM decisions — exactly as ``_regime_defensibility_entry`` /
    ``_relative_strength_defensibility_entry`` / ``_forecast_defensibility_entry``
    mirror their live counterparts.

    Cites ONLY the declared plan and the Trade_Manager output — never fabricates
    an exit: the simulated ``Exit_Breakdown`` + ``Realized_R`` are included only
    when a ``sim_result`` is supplied (managed trades); a single-target trade
    records the plan as single-target with no fabricated scale-out legs.
    """
    legs = [{"target": leg.target, "fraction": leg.fraction} for leg in (plan.legs or ())]
    breakeven = None
    if plan.breakeven is not None:
        breakeven = {"price": plan.breakeven.price, "r_multiple": plan.breakeven.r_multiple}
    trailing = None
    if plan.trailing is not None:
        trailing = {"atr_multiple": plan.trailing.atr_multiple, "r_increment": plan.trailing.r_increment}

    entry = {
        "available": True,
        # The single fixed-enumeration management-style value (R7.3, R11.2); the
        # journal namespaces it as ``tm:<style>`` at its fixed tag position.
        "style": trade_manager.management_style_tag(plan),
        "action": plan.action,
        "entry": plan.entry,
        "initial_stop": plan.initial_stop,
        "legs": legs,
        "breakeven": breakeven,
        "trailing": trailing,
        "atr_14": plan.atr_14,
    }
    # Where the plan was simulated (managed trades), cite the real Exit_Breakdown
    # + Realized_R verbatim from the Trade_Manager output (no fabrication).
    if sim_result is not None:
        entry["status"] = sim_result.status
        entry["realized_r"] = sim_result.realized_r
        entry["residual_fraction"] = sim_result.residual_fraction
        entry["exit_breakdown"] = [
            {
                "index": f.index,
                "price": f.price,
                "fraction": f.fraction,
                "leg_r": f.leg_r,
                "timestamp_ms": f.timestamp_ms,
                "kind": f.kind,
            }
            for f in sim_result.fills
        ]
    return entry


# ── Orchestration ─────────────────────────────────────────────────────────────

def generate_and_score(candles: List[dict], symbol: str, timeframe: str,
                       cfg: BacktestConfig,
                       benchmark_candles: Optional[List[dict]] = None,
                       benchmark: Optional[str] = None) -> List[dict]:
    """Walk the candle history, emit rule-based signals, and score each one.

    Returns a list of result records: {decision, status, outcome_price,
    outcome_at, r_multiple}. Pure given the candle data (no DB / network).

    ``benchmark_candles`` is the Benchmark_Index series for the run (resolved once
    by the caller, e.g. ``seed``, via ``_resolve_candles`` for the benchmark
    symbol/timeframe). When omitted, relative strength degrades to an honest
    Unavailable_Marker for every signal (no benchmark to compare against) and the
    seeded trades are tagged ``rs:unknown`` — the without-data behaviour stays
    unchanged.
    """
    results: List[dict] = []
    n = len(candles)
    if n < cfg.lookback + 2:
        return results

    # Resolve the regime thresholds ONCE, reusing the SAME resolver the live
    # get_market_regime tool uses (R10.5, R11.6) — the seeder never reimplements
    # the regime math.
    regime_config = regime.resolve_regime_config()

    # Resolve the relative-strength parameters ONCE, reusing the SAME resolver the
    # live get_relative_strength tool uses (R11.5, R12.6) — the seeder never
    # reimplements the relative-strength math. The Benchmark_Index is likewise
    # resolved once per run (R11.1).
    rs_config = rs.resolve_rs_config()
    if benchmark is None:
        benchmark = rs.resolve_benchmark(symbol)

    # Resolve the forecaster parameters ONCE, reusing the SAME resolver the live
    # get_forecast tool uses (R13.5, R14.5) — the seeder never reimplements the
    # forecast math. Each signal's forecast is computed point-in-time from this
    # single resolved config.
    forecaster_config = forecaster.resolve_forecaster_config()

    # Resolve the Trade_Manager parameters ONCE, reusing the SAME resolver the
    # live journal-scoring path uses (R13.5) — the seeder never reimplements the
    # exit-simulation math nor its parameter resolution. Managed seeded trades are
    # scored by feeding this single resolved config (and the default plan built
    # from it) to ``trade_manager.simulate_plan`` (R7.1, R7.2, AD-2).
    trade_manager_config = trade_manager.resolve_trade_manager_config()

    # Resolve the session parameters ONCE, reusing the SAME resolver the live
    # get_session_context tool uses (R11.6, R12.6) — the seeder never reimplements
    # the session date math. Each signal's session is classified point-in-time
    # from the timestamp of its OWN candle using this single resolved config.
    session_config = session.resolve_session_config()

    cooldown_until = -1
    for i in range(cfg.lookback - 1, n - 1):
        if i < cooldown_until:
            continue
        window = candles[i - cfg.lookback + 1: i + 1]
        ts = candles[i].get("timestamp_ms")
        created_at = (ts / 1000.0) if _is_num(ts) else 0.0
        decision = _signal_for_bar(window, created_at, cfg)
        if decision is None:
            continue

        # Classify the signal's regime using ONLY candles at or before the
        # signal's candle (index ``i``) — the point-in-time slice ``candles[:i+1]``
        # carries no later candles, so there is no look-ahead (R10.1). The same
        # classifier as the live tool path produces the label (R10.5).
        regime_result = regime.classify_regime(
            candles[: i + 1], regime_config, symbol=symbol, timeframe=timeframe
        )
        # Label the seeded trade with its Regime_Label so journal._regime_tag can
        # tag it (R10.3); shape mirrors graph._regime_entry.
        decision.setdefault("defensibility", {})["regime"] = _regime_defensibility_entry(regime_result)

        # Classify the signal's relative strength look-ahead-free (R11.1). Both
        # series are sliced to timestamps AT OR BEFORE the signal candle's
        # timestamp: the symbol series is index-sliced ``candles[:i+1]`` (already
        # point-in-time, ascending), and the SEPARATE benchmark series is filtered
        # by ``timestamp_ms <= signal ts`` since it cannot be index-aligned. The
        # signal's direction (BUY/SELL) is passed as ``proposed_direction``. The
        # SAME calculator as the live tool path produces the label (R11.5);
        # ``classify_relative_strength`` time-aligns the two windows internally.
        symbol_window = candles[: i + 1]
        benchmark_window = _candles_at_or_before(benchmark_candles, ts)
        rs_result = rs.classify_relative_strength(
            symbol_window, benchmark_window, rs_config,
            proposed_direction=decision.get("action"),
            symbol=symbol, benchmark=benchmark, timeframe=timeframe,
        )
        # Label the seeded trade with its Relative_Strength_Label so
        # journal._relative_strength_tag can tag it (R11.3); shape mirrors
        # graph._relative_strength_entry.
        decision["defensibility"]["relative_strength"] = _relative_strength_defensibility_entry(rs_result)

        # Classify the signal's forecast look-ahead-free (R13.1): the
        # Volatility_Aware_Forecaster sees ONLY candles AT OR BEFORE the signal
        # candle (the point-in-time slice ``candles[:i+1]`` carries no later
        # candles), and the signal's direction (BUY/SELL) is passed as
        # ``proposed_direction`` so the Forecast_Alignment is computed against the
        # trade. The SAME forecaster as the live tool path produces the label
        # (R13.5); the seeder never reimplements the forecast math.
        fc_result = forecaster.forecast(
            candles[: i + 1], forecaster_config,
            proposed_direction=decision.get("action"),
            symbol=symbol, timeframe=timeframe,
        )
        # Label the seeded trade with its Forecast_Label so journal._forecast_tag
        # can tag it and journal.record_backtest_trade persists its Up_Probability
        # (R11.4); shape mirrors graph._forecast_entry.
        decision["defensibility"]["forecast"] = _forecast_defensibility_entry(fc_result)

        # Classify the signal's session using the timestamp of the signal's OWN
        # candle (index ``i``) via the SAME classifier as the live tool path
        # (R11.1, R11.6). A candle's timestamp is intrinsic to that candle, so
        # this is inherently look-ahead-free — no later candle informs the label.
        session_result = session.classify_session(
            ts, session_config, symbol=symbol, timeframe=timeframe,
        )
        # Label the seeded trade with its Session_Phase and expiry flag so
        # journal._session_tag can tag it (R11.3); shape mirrors graph._session_entry.
        decision["defensibility"]["session"] = _session_defensibility_entry(session_result)

        # ── Score the signal (managed via the Trade_Manager, else single-target) ─
        # A managed run (``cfg.manage_trades``) attaches the uniform default
        # Management_Plan built from the resolved Trade_Manager config and scores
        # it with ``trade_manager.simulate_plan`` against the candles after the
        # entry bar (R7.1) — reusing the SINGLE source of truth for the exit math
        # rather than reimplementing it (R7.2). A single-target run keeps the
        # legacy ``_score_signal`` path so its outcome is byte-for-byte today's.
        future = candles[i + 1:]
        if cfg.manage_trades:
            plan = trade_manager.default_management_plan(
                decision["action"], decision["entry"], decision["stop_loss"],
                decision.get("atr_14"), trade_manager_config,
            )
            scored, sim_result = _score_signal_managed(plan, future, cfg, trade_manager_config)
        else:
            # Single_Target_Trade: the degenerate one-leg plan models today's
            # bracket purely for the management-style label; scoring stays on the
            # existing conservative ``_score_signal`` path (R3.6 / R14.5).
            plan = trade_manager.single_target_plan(
                decision["entry"], decision["stop_loss"], decision["take_profit"],
            )
            sim_result = None
            scored = _score_signal(decision, future, cfg)
        if scored is None:
            continue
        status, out_price, out_at, r_mult = scored

        # Label the seeded trade with its management style (R7.3) and cite the
        # plan (and, for a managed trade, the simulated Exit_Breakdown + Realized_R)
        # in the defensibility record. The journal's public seeding API
        # (``record_backtest_trade``) receives this whole ``decision`` dict, so the
        # management style/tag is threaded into the journal's management-style
        # fingerprint without editing journal.py.
        decision["defensibility"]["management"] = _management_defensibility_entry(plan, sim_result)
        decision["management_plan"] = trade_manager.plan_to_json(plan)

        # When the gate is enabled, DROP a signal whose regime favorability is an
        # AVAILABLE "unfavorable" label for its setup type (R10.2). Signals whose
        # regime is an Unavailable_Marker are RETAINED — never excluded on the
        # basis of regime (R10.6) — as are favorable/neutral signals. The drop
        # still advances the cooldown exactly as a taken signal would, so the
        # with-gate run walks the IDENTICAL history/rules as the without-gate run
        # and its seeded set is a strict SUBSET of the without-gate set (R10.4).
        gated_out = cfg.regime_gate_enabled and _signal_is_unfavorable(decision)

        # ── Relative-strength filter (with-filter run only) ──────────────────
        # When the filter is enabled, DROP a signal whose relative-strength
        # Alignment is an AVAILABLE "misaligned" label for its direction (R11.2).
        # Signals whose relative strength is an Unavailable_Marker are RETAINED —
        # never excluded on the basis of relative strength being unavailable
        # (R11.6) — as are aligned/neutral signals. The drop advances the cooldown
        # exactly as a taken signal would, mirroring the regime gate, so the
        # with-filter run walks the IDENTICAL history/rules as the without-filter
        # run and its seeded set is a strict SUBSET of the without-filter set.
        filtered_out = cfg.rs_filter_enabled and _signal_is_misaligned(decision)

        # ── Forecast filter (with-forecast run only) ─────────────────────────
        # When the forecast filter is enabled, DROP a signal whose
        # Forecast_Alignment is an AVAILABLE "misaligned" label for its direction
        # (R13.2). Signals whose forecast is an Unavailable_Marker are RETAINED —
        # never excluded on the basis of the forecast being unavailable (R13.4) —
        # as are aligned/neutral signals. The drop advances the cooldown exactly
        # as a taken signal would, mirroring the regime gate and RS filter, so the
        # with-forecast run walks the IDENTICAL history/rules as the
        # without-forecast run and its seeded set is a strict SUBSET of it.
        forecast_filtered_out = cfg.forecast_filter_enabled and _signal_is_forecast_misaligned(decision)

        # ── Session filter (with-filter run only) ────────────────────────────
        # When the session filter is enabled, DROP a signal whose Time_Favorability
        # is an AVAILABLE "unfavorable" label for its time window (R11.2). Signals
        # whose session result is an Unavailable_Marker are RETAINED — never
        # excluded on the basis of the session being unavailable (R11.5) — as are
        # favorable/neutral signals. The drop advances the cooldown exactly as a
        # taken signal would, mirroring the regime gate and the RS/forecast
        # filters, so the with-filter run walks the IDENTICAL history/rules as the
        # without-filter run and its seeded set is a strict SUBSET of it.
        session_filtered_out = cfg.session_filter_enabled and _signal_is_session_unfavorable(decision)

        if gated_out or filtered_out or forecast_filtered_out or session_filtered_out or (status == "expired" and not cfg.record_unresolved):
            cooldown_until = i + cfg.cooldown_bars
            continue
        results.append({
            "decision": decision,
            "status": status,
            "outcome_price": out_price,
            "outcome_at": out_at,
            "r_multiple": r_mult,
        })
        cooldown_until = i + cfg.cooldown_bars
    return results


def _fetch_candles(symbol: str, timeframe: str, limit: int) -> List[dict]:
    r = httpx.post(
        f"{RUST_SERVER_URL}/tools/get_candles",
        json={"symbol": symbol, "timeframe": timeframe, "limit": limit},
        timeout=20.0,
    )
    r.raise_for_status()
    data = r.json()
    if not isinstance(data, list):
        raise RuntimeError(f"Unexpected candle payload: {type(data).__name__}")
    return data


def _fetch_candles_questdb(symbol: str, timeframe: str, limit: int) -> List[dict]:
    """Read historical candles directly from QuestDB's HTTP query API.

    Daily/weekly timeframes come from ``historical_candles``; all other (intraday)
    timeframes from ``historical_intraday`` filtered by its ``timeframe`` column.
    ``CAST(ts AS LONG)`` yields microseconds since epoch (QuestDB's native unit),
    which we convert to the milliseconds the rest of the pipeline expects.
    ``ORDER BY ts LIMIT -N`` returns the most recent N rows in ascending order.
    """
    sym = symbol.replace("'", "''")  # escape for the SQL string literal
    tf = (timeframe or "").strip().lower()
    if tf in _DAILY_TIMEFRAMES:
        query = (
            "SELECT CAST(ts AS LONG) AS ts_us, open, high, low, close, volume "
            f"FROM historical_candles WHERE symbol='{sym}' ORDER BY ts LIMIT -{int(limit)}"
        )
    else:
        tf_lit = timeframe.replace("'", "''")
        query = (
            "SELECT CAST(ts AS LONG) AS ts_us, open, high, low, close, volume "
            f"FROM historical_intraday WHERE symbol='{sym}' AND timeframe='{tf_lit}' "
            f"ORDER BY ts LIMIT -{int(limit)}"
        )

    r = httpx.get(f"{QUESTDB_HTTP_URL}/exec", params={"query": query}, timeout=30.0)
    r.raise_for_status()
    body = r.json()
    if isinstance(body, dict) and body.get("error"):
        raise RuntimeError(f"QuestDB query error: {body.get('error')} (table may not exist or be empty)")
    dataset = body.get("dataset") if isinstance(body, dict) else None
    if not dataset:
        raise RuntimeError(
            f"QuestDB returned no rows for {symbol}/{timeframe}. "
            f"Has historical data been loaded for this symbol/timeframe?"
        )

    candles: List[dict] = []
    for row in dataset:
        if len(row) < 6 or row[0] is None:
            continue
        candles.append({
            "timestamp_ms": float(row[0]) / 1000.0,  # micros -> millis
            "open": row[1], "high": row[2], "low": row[3],
            "close": row[4], "volume": row[5] if row[5] is not None else 0.0,
        })
    return candles


def _resolve_candles(symbol: str, timeframe: str, limit: int, source: str) -> List[dict]:
    """Resolve candles from the requested source.

    ``auto`` (default) tries QuestDB first (works without the Tauri app), then
    falls back to the Rust tool server. ``questdb`` / ``server`` force one path.
    """
    if source == "questdb":
        return _fetch_candles_questdb(symbol, timeframe, limit)
    if source == "server":
        return _fetch_candles(symbol, timeframe, limit)
    # auto
    try:
        return _fetch_candles_questdb(symbol, timeframe, limit)
    except Exception as qe:
        print(f"[Backtest_Seeder] QuestDB source unavailable ({qe}); trying Rust tool server...")
        return _fetch_candles(symbol, timeframe, limit)


def _resolve_benchmark_candles(benchmark: str, timeframe: str, limit: int,
                               source: str) -> Optional[List[dict]]:
    """Resolve the Benchmark_Index candle series for a run.

    Mirrors how the symbol candles are resolved (``_resolve_candles`` for the
    benchmark symbol / same timeframe / same limit), so the relative-strength
    calculator compares like-for-like windows. Degrades to ``None`` on any
    retrieval failure (e.g. no history loaded for the benchmark) so the run still
    proceeds — relative strength then reports an honest Unavailable_Marker for
    every signal rather than aborting the seeding (R11.6, AD-4). Never raises.
    """
    if not isinstance(benchmark, str) or not benchmark.strip():
        return None
    try:
        return _resolve_candles(benchmark.strip(), timeframe, limit, source)
    except Exception as e:  # benchmark history may be absent — non-fatal.
        print(f"[Backtest_Seeder] benchmark candles for {benchmark!r} unavailable "
              f"({e}); relative strength will be reported as unavailable.")
        return None


def _load_candles_file(path: str) -> List[dict]:
    with open(path, "r", encoding="utf-8") as fh:
        data = json.load(fh)
    if isinstance(data, dict) and isinstance(data.get("candles"), list):
        data = data["candles"]
    if not isinstance(data, list):
        raise RuntimeError("candles file must be a JSON list (or {\"candles\": [...]})")
    return data


def seed(symbol: str, timeframe: str, limit: int = 3000,
         candles: Optional[List[dict]] = None, cfg: Optional[BacktestConfig] = None,
         purge_first: bool = True, dry_run: bool = False, source: str = "auto") -> dict:
    """Generate, score, and (unless dry_run) write backtest trades to the journal.

    Returns a summary dict with the number of trades by outcome plus the
    resulting backtest-only stats from the journal.
    """
    cfg = cfg or BacktestConfig()
    if candles is None:
        candles = _resolve_candles(symbol, timeframe, limit, source)

    # Resolve the Benchmark_Index and its candle series once for the run so each
    # signal's relative strength is classified look-ahead-free against it (R11.1).
    benchmark = rs.resolve_benchmark(symbol)
    benchmark_candles = _resolve_benchmark_candles(benchmark, timeframe, limit, source)

    results = generate_and_score(
        candles, symbol, timeframe, cfg,
        benchmark_candles=benchmark_candles, benchmark=benchmark,
    )
    wins = sum(1 for r in results if r["status"] == "win")
    losses = sum(1 for r in results if r["status"] == "loss")
    expired = sum(1 for r in results if r["status"] == "expired")

    summary = {
        "symbol": symbol,
        "timeframe": timeframe,
        "candles": len(candles),
        "signals_scored": len(results),
        "wins": wins,
        "losses": losses,
        "expired": expired,
        "dry_run": dry_run,
    }

    if dry_run:
        summary["note"] = "dry-run: no journal writes performed"
        return summary

    if purge_first:
        removed = journal.purge(source="backtest", symbol=symbol)
        summary["purged_existing_backtest"] = removed

    written = 0
    for r in results:
        rid = journal.record_backtest_trade(
            r["decision"], symbol=symbol, timeframe=timeframe,
            status=r["status"], outcome_price=r["outcome_price"],
            outcome_at=r["outcome_at"], r_multiple=r["r_multiple"],
        )
        if rid is not None:
            written += 1
    summary["written"] = written
    summary["stats"] = journal.get_stats(symbol=symbol, source="backtest")
    return summary


# ── With-gate / without-gate comparison (R10.4, R10.7) ───────────────────────

def _run_metrics(results: List[dict]) -> dict:
    """Compute a single run's win-rate and expectancy over its CLOSED trades.

    A trade is *closed* when it resolved by hitting its stop or target — i.e.
    ``status`` is ``win`` or ``loss`` and carries a realized R-multiple. Expired
    (unresolved) trades are NOT closed and are excluded from both metrics.

      * win_rate   = winning closed trades / closed trades
      * expectancy = mean realized R-multiple per closed trade

    When a run has ZERO closed trades, BOTH metrics are reported as ``"n/a"``
    rather than computing a division by zero (R10.7).
    """
    closed = [r for r in results if r["status"] in ("win", "loss") and _is_num(r.get("r_multiple"))]
    n_closed = len(closed)
    if n_closed == 0:
        return {
            "closed_trades": 0,
            "winning_closed_trades": 0,
            "win_rate": "n/a",
            "expectancy": "n/a",
        }
    winning = sum(1 for r in closed if r["status"] == "win")
    expectancy = sum(r["r_multiple"] for r in closed) / n_closed
    return {
        "closed_trades": n_closed,
        "winning_closed_trades": winning,
        "win_rate": round(winning / n_closed, 4),
        "expectancy": round(expectancy, 4),
    }


def compare(symbol: str, timeframe: str, limit: int = 3000,
            candles: Optional[List[dict]] = None, cfg: Optional[BacktestConfig] = None,
            source: str = "auto") -> dict:
    """Run the backtest WITH and WITHOUT the regime gate and compare them (R10.4).

    Both runs use the IDENTICAL candle history and IDENTICAL setup rules — only
    ``regime_gate_enabled`` differs — so the two runs are directly comparable and
    the with-gate seeded set is a strict subset of the without-gate set (the gate
    only removes signals whose regime favorability is the available ``unfavorable``
    label; Unavailable_Marker signals are retained — R10.2, R10.6).

    Returns a summary reporting, for EACH run, the win-rate (winning closed /
    closed) and expectancy (mean realized R per closed trade), with ``"n/a"`` when
    a run produced zero closed trades (R10.7). Pure given ``candles`` — no journal
    writes are performed.
    """
