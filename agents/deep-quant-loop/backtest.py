"""Backtest_Seeder — give the Deep Quant agent a track record on day one.

Phase 2.5 of the trading-edge roadmap. The live Trade_Journal (journal.py) only
learns as real trades accumulate and resolve, which means the agent's
`get_trade_performance` is empty until then. This seeder replays HISTORICAL
candles through a set of deterministic, rule-based setups and scores them with
the SAME conservative outcome logic the live journal uses, then writes the
resolved trades into the journal tagged ``source='backtest'``.

Why this is honest and useful:
  * The seeded trades are tagged with the SAME setup fingerprint
    (direction / macro alignment / predictive agreement / value-area location)
    as live LLM decisions, so per-setup statistics are directly comparable and
    give the agent a meaningful PRIOR on which setup *types* historically work.
  * Scoring uses the same worst-case fill assumption (a candle that straddles
    both stop and target counts as a loss), so the prior never flatters itself.
  * Seeded rows carry ``source='backtest'`` so they are always distinguishable
    from — and purgeable independently of — live trades.

IMPORTANT CAVEAT (surfaced to the user): the seeder's setups are generated by
simple deterministic RULES, not by the LLM agent. So the prior reflects how a
*setup type* behaves historically, not how this specific model would trade. It
is a starting calibration, not ground truth for the agent's own edge — live
trades gradually dominate the statistics.

Usage:
    python backtest.py --symbol RELIANCE --timeframe 15m --limit 3000
    python backtest.py --symbol RELIANCE --timeframe 1d --candles-file hist.json
    python backtest.py --symbol RELIANCE --timeframe 15m --dry-run   # no DB writes
"""

